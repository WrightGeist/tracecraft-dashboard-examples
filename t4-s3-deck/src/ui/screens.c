void tick_screen_main() {
    {
        int32_t new_val = get_var_rpm();
        int32_t cur_val = lv_arc_get_value(objects.rpm_arc);
        if (new_val != cur_val) {
            tick_value_change_obj = objects.rpm_arc;
            lv_arc_set_value(objects.rpm_arc, new_val);
            tick_value_change_obj = NULL;
        }
    }
    {
        const char *new_val = get_var_gear();
        const char *cur_val = lv_label_get_text(objects.gear_label);
        if (strcmp(new_val, cur_val) != 0) {
            tick_value_change_obj = objects.gear_label;
            lv_label_set_text(objects.gear_label, new_val);
            tick_value_change_obj = NULL;
        }
    }
    {
        const char *new_val = get_var_speed();
        const char *cur_val = lv_label_get_text(objects.speed_label);
        if (strcmp(new_val, cur_val) != 0) {
            tick_value_change_obj = objects.speed_label;
            lv_label_set_text(objects.speed_label, new_val);
            tick_value_change_obj = NULL;
        }
    }
    {
        int32_t new_val = get_var_fuel_pct();
        int32_t cur_val = lv_bar_get_value(objects.fuel_bar);
        if (new_val != cur_val) {
            tick_value_change_obj = objects.fuel_bar;
            lv_bar_set_value(objects.fuel_bar, new_val, LV_ANIM_OFF);
            tick_value_change_obj = NULL;
        }
    }
}

typedef void (*tick_screen_func_t)();
tick_screen_func_t tick_screen_funcs[] = {
    tick_screen_main,
};
void tick_screen(int screen_index) {
    if (screen_index >= 0 && screen_index < 1) {
        tick_screen_funcs[screen_index]();
    }
}
void tick_screen_by_id(enum ScreensEnum screenId) {
    tick_screen(screenId - 1);
}

